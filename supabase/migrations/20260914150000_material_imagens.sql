Composição e segmentos do Sistema Financeiro Nacional

Segmento "Moeda, crédito, capitais e câmbio":
- Órgão normativo: CMN (Conselho Monetário Nacional).
- Supervisores: BCB (Banco Central do Brasil) e CVM (Comissão de Valores Mobiliários).
- Operadores na coluna do BCB: bancos e caixas econômicas; administradoras de consórcios; cooperativas de crédito; corretoras e distribuidoras; instituições de pagamento; demais instituições não bancárias.
- Operadores na coluna da CVM: bolsa de valores; bolsa de mercadorias e futuros.

Segmento "Seguros privados":
- Órgão normativo: CNSP (Conselho Nacional de Seguros Privados).
- Supervisor: Susep (Superintendência de Seguros Privados).
- Operadores: seguradoras e resseguradores; entidades abertas de previdência; sociedades de capitalização.

Segmento "Previdência fechada":
- Órgão normativo: CNPC (Conselho Nacional de Previdência Complementar).
- Supervisor: Previc (Superintendência Nacional de Previdência Complementar).
- Operadores: entidades fechadas de previdência complementar (fundos de pensão).

Observações constantes do próprio quadro:
* Dependendo de suas atividades, corretoras e distribuidoras também são fiscalizadas pela CVM.
** As Instituições de Pagamento não compõem o SFN, mas são reguladas e fiscalizadas pelo BCB, conforme diretrizes estabelecidas pelo CMN.

