A estrutura organizacional do Coaf

Organograma do Coaf:
- Coaf
  - Plenário
  - Quadro Técnico
    - Inteligência Financeira
    - Supervisão
    - Gestão e Articulação

O artigo 4º da Lei nº 13.974, de 2020, manteve no Coaf organização similar à já existente, consistindo da Presidência e de duas principais estruturas: o Plenário e o Quadro Técnico.

Plenário: o Plenário é um conjunto de conselheiros que se reúne periodicamente para definir as diretrizes estratégicas de atuação do Coaf. O Plenário também é responsável por aprovar normas e julgar processos administrativos sancionadores, aplicáveis às pessoas obrigadas supervisionadas pelo Coaf que infringiram a legislação de prevenção à lavagem de dinheiro e ao financiamento do terrorismo.

Quadro Técnico: é o quadro de servidores que trabalham no Coaf. Essas equipes são responsáveis pelos processos de análise de informações recebidas dos setores obrigados, de produção dos Relatórios de Inteligência Financeira (RIF), de supervisão de setores obrigados sem regulador próprio, de desenvolvimento de modelos estatísticos e de machine learning, de gestão e articulação institucional, entre outras atividades.

Pergunta: O Plenário possui acesso aos Relatórios de Inteligência Financeira (RIF) do Coaf?
Resposta: NÃO. A produção dos RIF é competência exclusiva do quadro técnico e é protegida por sigilo legal.

